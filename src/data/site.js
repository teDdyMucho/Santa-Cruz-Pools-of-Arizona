/* ---------- Media helpers ---------- */
const src = (name, w) => `/media/${name}-${w}.webp`

/** Everything an <img> needs, with a srcSet limited to widths that exist. */
export function imageProps(name, sizes = '100vw') {
  const m = manifest[name]
  if (!m) {
    if (import.meta.env.DEV) console.warn(`[media] unknown image "${name}"`)
    return { src: '', srcSet: undefined, sizes, width: undefined, height: undefined }
  }
  return {
    src: src(name, m.widths[m.widths.length - 1]),
    srcSet: m.widths.map((w) => `${src(name, w)} ${w}w`).join(', '),
    sizes,
    width: m.w,
    height: m.h,
  }
}

